#!/usr/bin/env node
// Turn tools/db/dump.sql's output into one migration that rebuilds everything
// Lektionskollen owns, from nothing.
//
//   node tools/db/baseline.mjs dump.json > supabase/migrations/<stamp>_lk_baseline.sql
//
// Every statement is safe to run on a database that already has it (if not
// exists, create or replace, guarded constraints), so the baseline can be
// applied to the live project as a no-op as well as to an empty one.
import { readFileSync } from 'node:fs';

const raw = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const d = typeof raw.dump === 'string' ? JSON.parse(raw.dump) : raw;
const out = [];
const say = (s = '') => out.push(s);
const lit = (s) => "'" + String(s).replace(/'/g, "''") + "'";

say('-- Lektionskollen: the whole schema, from nothing. Generated by tools/db/baseline.mjs');
say('-- from tools/db/dump.sql run against the live project. Do not edit by hand:');
say('-- change the database with a new migration after this one, and re-baseline');
say('-- only when the archive of old migrations gets in the way.');
say('--');
say('-- Safe on an empty database and on the live one (where it changes nothing).');
say('-- Needs what Supabase provides: roles anon/authenticated/service_role, the');
say('-- auth schema, pgcrypto in the extensions schema, and (optionally) pg_cron.');
say();
say("set check_function_bodies = off;");
say("set search_path = public, extensions;");
say('create schema if not exists lektionskollen;');
say();

say('-- ── Sequences ──');
for (const s of d.seqs ?? []) say(`create sequence if not exists lektionskollen.${s.s};`);
say();

say('-- ── Tables ──');
for (const t of d.tables) {
  const cols = t.cols.map((c) => {
    let x = `  ${c.n} ${c.ty}`;
    if (c.id === 'a') x += ' generated always as identity';
    else if (c.id === 'd') x += ' generated by default as identity';
    else if (c.d) x += ` default ${c.d}`;
    if (c.nn) x += ' not null';
    return x;
  });
  say(`create table if not exists lektionskollen.${t.t} (\n${cols.join(',\n')}\n);`);
}
for (const s of d.seqs ?? []) if (s.owner) say(`alter sequence lektionskollen.${s.s} owned by lektionskollen.${s.owner};`);
say();

say('-- ── Keys and checks, then foreign keys ──');
for (const c of d.cons) {
  say(`do $$ begin\n  if not exists (select 1 from pg_constraint where conname = ${lit(c.n)} and conrelid = ${lit(c.tbl)}::regclass) then\n` +
      `    alter table ${c.tbl} add constraint ${c.n} ${c.def};\n  end if;\nend $$;`);
}
say();

say('-- ── Indexes ──');
for (const i of d.idx ?? []) say(i.replace(/^CREATE (UNIQUE )?INDEX /, (_m, u) => `CREATE ${u ?? ''}INDEX IF NOT EXISTS `) + ';');
say();

say('-- ── Row-level security: on, with no policies. Everything goes through the');
say('--    security-definer lk_* functions; the tables themselves are closed. ──');
for (const t of d.tables) if (t.rls) say(`alter table lektionskollen.${t.t} enable row level security;`);
say();

say('-- ── Functions ──');
for (const f of d.fns) say(f.def.trim() + ';\n');

say('-- ── Who may call what. Explicit, because Supabase grants new functions to');
say('--    anon and authenticated by default. ──');
for (const f of d.fns) {
  say(`revoke all on function ${f.sig} from public, anon, authenticated;`);
  const to = (f.acl ?? []).filter((r) => ['anon', 'authenticated', 'service_role'].includes(r));
  if (to.length) say(`grant execute on function ${f.sig} to ${to.join(', ')};`);
}
say();

say('-- ── Triggers ──');
for (const t of d.trg ?? []) {
  const m = /^CREATE TRIGGER (\S+) .* ON (\S+) /.exec(t);
  if (m) say(`drop trigger if exists ${m[1]} on ${m[2]};`);
  say(t + ';');
}
say();

say('-- ── Nightly jobs (only where pg_cron is installed) ──');
for (const j of d.cron ?? []) {
  say(`do $$ begin\n  if exists (select 1 from pg_extension where extname = 'pg_cron') then\n` +
      `    perform cron.unschedule(${lit(j.n)}) where exists (select 1 from cron.job where jobname = ${lit(j.n)});\n` +
      `    perform cron.schedule(${lit(j.n)}, ${lit(j.s)}, ${lit(j.c)});\n  end if;\nend $$;`);
}
process.stdout.write(out.join('\n') + '\n');
