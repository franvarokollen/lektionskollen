#!/usr/bin/env node
// Export the authored lesson content from the database into the repo, so the
// 26 topics are version-controlled rather than living only in Supabase.
//
//   SUPABASE_URL=... SUPABASE_SERVICE_KEY=... node tools/dump-content.mjs
//
// Writes supabase/seed/sim_content.sql, which is idempotent (on conflict do
// update) and can be replayed into a fresh project.

import { writeFileSync, mkdirSync } from 'node:fs';

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_KEY;
if (!url || !key) {
  console.error('Set SUPABASE_URL and SUPABASE_SERVICE_KEY.');
  process.exit(1);
}

// lektionskollen is not exposed to PostgREST by design, so this goes through a
// plain SQL call rather than the table API.
const res = await fetch(`${url.replace(/\/$/, '')}/rest/v1/rpc/lk_dump_content`, {
  method: 'POST',
  headers: { apikey: key, Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
  body: '{}',
});
if (!res.ok) {
  console.error(`Dump failed: ${res.status} ${await res.text()}`);
  console.error('Needs: create function public.lk_dump_content() returns setof lektionskollen.sim_content');
  console.error('       language sql security definer as $$ select * from lektionskollen.sim_content order by key $$;');
  process.exit(1);
}

const rows = await res.json();
const q = (s) => `$j$${s}$j$`;
const out = [
  '-- Generated by tools/dump-content.mjs. Do not edit by hand.',
  `-- ${rows.length} topics, both languages.`,
  '',
  'insert into lektionskollen.sim_content (key, subject, year_group, minutes, sv, en) values',
  rows.map((r) =>
    `('${r.key}','${r.subject}','${r.year_group}',${r.minutes},\n` +
    `${q(JSON.stringify(r.sv))},\n${q(JSON.stringify(r.en))})`).join(',\n'),
  'on conflict (key) do update set',
  '  subject = excluded.subject, year_group = excluded.year_group,',
  '  minutes = excluded.minutes, sv = excluded.sv, en = excluded.en, updated_at = now();',
  '',
].join('\n');

mkdirSync('supabase/seed', { recursive: true });
writeFileSync('supabase/seed/sim_content.sql', out);
console.log(`Wrote supabase/seed/sim_content.sql — ${rows.length} topics.`);
